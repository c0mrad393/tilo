const KINDS: [ClaimKind, string, string][] = [
  ["copyright", "Copyright", "It's my work, or the work of someone I act for, shown without permission."],
  ["abuse", "Abuse", "It breaks Tilo's rules: not for all ages, hateful, harassing, or against the law."],
  ["privacy", "Privacy", "It shows me, or something private about me, without my agreement."],
  ["other", "Something else", "Say what in the details."],
];

function ClaimForm() {
  const id = useId();
  const { search } = useLocation();
  const [kind, setKind] = useState<ClaimKind | "">("");
  const [url, setUrl] = useState(() => new URLSearchParams(search).get("url") ?? "");
  const [name, setName] = useState("");
  const [email, setEmail] = useState("");
  const [details, setDetails] = useState("");
  const [sworn, setSworn] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<{ field?: string; text: string } | null>(null);
  const [sent, setSent] = useState<number | null>(null);

  const send = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!kind) return setError({ field: "kind", text: "Say what kind of claim it is." });
    setBusy(true);
    setError(null);
    try {
      setSent((await sendClaim({ kind, url, name, email, details, sworn })).id);
    } catch (err) {
      const hint = (err as { hint?: string }).hint;
      setError({ field: hint, text: err instanceof Error ? err.message : "That didn't go through. Try again, or write to us." });
    } finally {
      setBusy(false);
    }
  };
  if (sent !== null)
    return (
      <div className="claim-sent" role="status">
        <h3>Thank you. Your claim is number {sent}.</h3>
        <p className="serif">We'll answer at {email} within {ANSWER_IN}. Quote the number if you write to <Mail to={LEGAL} /> about it.</p>
      </div>
    );
  const err = (field: string) =>
    error?.field === field ? <span className="field-note is-error" id={`${id}-${field}-e`} role="alert">{error.text}</span> : null;
  const invalid = (field: string) => (error?.field === field ? { "aria-invalid": true, "aria-describedby": `${id}-${field}-e` } : {});
  return (
    <form className="claim-form" onSubmit={send} noValidate>
      <fieldset className="report-reasons">
        <legend className="kicker">What kind of claim</legend>
        {KINDS.map(([k, label, hint]) => (
          <label key={k} className="check">
            <input type="radio" name="kind" value={k} checked={kind === k} onChange={() => setKind(k)} />
            <span><b>{label}</b> <span className="field-note">{hint}</span></span>
          </label>
        ))}
        {err("kind")}
      </fieldset>
      <div className="field">
        <label htmlFor={`${id}-url`}>The piece or profile</label>
        <input id={`${id}-url`} value={url} required placeholder="https://tiloart.com/piece/…" onChange={(e) => setUrl(e.target.value)} {...invalid("url")} />
        {err("url")}
      </div>
      <div className="field">
        <label htmlFor={`${id}-name`}>Your name</label>
        <input id={`${id}-name`} value={name} required maxLength={120} autoComplete="name" onChange={(e) => setName(e.target.value)} {...invalid("name")} />
        {err("name")}
      </div>
      <div className="field">
        <label htmlFor={`${id}-email`}>Your email address</label>
        <input id={`${id}-email`} type="email" value={email} required maxLength={254} autoComplete="email" onChange={(e) => setEmail(e.target.value)} {...invalid("email")} />
        {err("email")}
      </div>
      <div className="field">
        <label htmlFor={`${id}-details`}>What's wrong</label>
        <textarea
          id={`${id}-details`}
          value={details}
          required
          rows={5}
          maxLength={4000}
          onChange={(e) => setDetails(e.target.value)}
          {...invalid("details")}
        />
        <span className="field-note">For copyright, say which work is yours and where it was first shown, with a link if there is one.</span>
        {err("details")}
      </div>
      {kind === "copyright" && (
        <label className="check claim-sworn">
          <input type="checkbox" checked={sworn} onChange={(e) => setSworn(e.target.checked)} {...invalid("sworn")} />
          <span>I believe in good faith that this use isn't allowed, and what I've said is accurate. I own the work or act for whoever does.</span>
        </label>
      )}
      {err("sworn")}
      {error && !["kind", "url", "name", "email", "details", "sworn"].includes(error.field ?? "") && (
        <p className="field-note is-error" role="alert">{error.text}</p>
      )}
      <div className="row row-start">
        <button className="btn btn-ink" disabled={busy}>{busy ? "Sending…" : "Send the claim"}</button>
      </div>
    </form>
  );
}

